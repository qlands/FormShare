"""One regeneration of a published list's file at a time (2026-10-19).

A device's manifest request regenerates a list that is older than its
source's last change (refresh_published_lists and refresh_list_variant in
processes/odk/api.py). Nothing stopped two devices pulling at once from both
regenerating it. That was twice the work, and the later write emptied the
file while the other's device downloaded it; with a submission between the
two, the list could end up missing a case while stamped current.

- **The lock.** A Redis key per copy of a list -- a form's copy, or a
  variant -- held by one request across every web worker, the export lock's
  way (products/block.py).
- **After waiting.** Whoever waited reads the list's state again once it
  holds the lock. The other request has usually regenerated it, and nothing
  is left to do.
- **No lock in time.** A request that cannot get it within lists.lock_wait
  seconds serves the list as it is: stale data a device can use beats a pull
  that fails.
- **A request that dies holding it.** Redis lets the key go after
  lists.lock_expire seconds, so nobody waits long.
- **Without Redis,** lists regenerate unlocked, as before.

caselistgen writes a list in a fraction of a second, so the lock is short.
"""

import logging
import time
import uuid
from contextlib import contextmanager

import redis

from formshare.products.block import get_redis_client

__all__ = ["list_lock", "form_copy_key", "variant_lock_key"]

log = logging.getLogger("formshare")

# Seconds a request waits for another's regeneration of the same list
LOCK_WAIT = 30
# Seconds Redis keeps the lock of a request that never let it go
LOCK_EXPIRE = 120
POLL = 0.1

# Lets the key go only if this request still holds it
_RELEASE = """
if redis.call("get", KEYS[1]) == ARGV[1] then
    return redis.call("del", KEYS[1])
end
return 0
"""


def form_copy_key(project_id, form_id, file_name):
    """A form's copy of a list served to everyone."""
    return "{}:{}:{}".format(project_id, form_id, file_name)


def variant_lock_key(project_id, list_id, variant):
    """A variant of a list served per assistant (variant_key)."""
    return "{}:{}:variant:{}".format(project_id, list_id, variant)


def _seconds(settings, name, default):
    try:
        return float(settings.get(name, default))
    except (TypeError, ValueError):
        return default


@contextmanager
def list_lock(settings, key, client=None):
    """Holds the regeneration lock of one copy of a list. Yields True when
    this request holds it, or regenerates unlocked because Redis is not
    there; False when another request held it past the wait, and the list is
    served as it is."""
    wait = _seconds(settings, "lists.lock_wait", LOCK_WAIT)
    expire = max(1, int(_seconds(settings, "lists.lock_expire", LOCK_EXPIRE)))
    lock_key = "list-lock:" + key
    token = uuid.uuid4().hex
    own_client = client is None
    if own_client:
        client = get_redis_client(settings)
    held = False
    unlocked = False
    try:
        deadline = time.monotonic() + wait
        while True:
            held = bool(client.set(lock_key, token, nx=True, ex=expire))
            if held or time.monotonic() >= deadline:
                break
            time.sleep(POLL)
    except redis.RedisError as e:
        log.error("List {} regenerates unlocked: Redis said {}".format(key, e))
        unlocked = True
    try:
        if not held and not unlocked:
            log.warning(
                "List {} was being regenerated by another request for longer "
                "than {} seconds: served as it is".format(key, wait)
            )
        yield held or unlocked
    finally:
        if held:
            try:
                client.eval(_RELEASE, 1, lock_key, token)
            except redis.RedisError as e:
                log.error("The lock of list {} could not be let go: {}".format(key, e))
        if own_client:
            client.close()
